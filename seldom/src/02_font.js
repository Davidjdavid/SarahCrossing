const FONT = {};    /* char -> { w, rows[8] of bits } */
(function buildFont() {
    for (const [chars, src] of FONT_SRC) {
        const lines = src.trim().split('\n');
        const glyphs = [...chars];
        glyphs.forEach((ch, gi) => {
            const rows = lines.map(l => l.slice(gi * 6, gi * 6 + 5));
            let w = 1;
            rows.forEach(r => { for (let i = 0; i < 5; i++) if (r[i] === '#') w = Math.max(w, i + 1); });
            FONT[ch] = { w, rows };
        });
    }
    FONT[' '] = { w: 3, rows: Array(8).fill('.....') };
})();
const fontAtlas = {};
function glyphCanvas(ch, color) {
    const key = ch + color;
    if (fontAtlas[key]) return fontAtlas[key];
    const g = FONT[ch] || FONT['?'];
    const c = document.createElement('canvas'); c.width = Math.max(1, g.w); c.height = 8;
    const x = c.getContext('2d'); x.fillStyle = color;
    g.rows.forEach((r, y) => { for (let i = 0; i < 5; i++) if (r[i] === '#') x.fillRect(i, y, 1, 1); });
    return (fontAtlas[key] = c);
}
function textWidth(s) { let w = 0; for (const ch of s) w += (FONT[ch] || FONT['?']).w + 1; return Math.max(0, w - 1); }
/* draw text at (x, y) top-left, s = screen pixels per font pixel; shadow draws a dark copy one pixel down */
function drawText(ctx, s, x, y, color, scale, shadow) {
    scale = scale || 1;
    if (shadow) drawText(ctx, s, x + scale, y + scale, shadow, scale);
    let cx = x;
    for (const ch of s) {
        const g = FONT[ch] || FONT['?'];
        if (ch !== ' ') ctx.drawImage(glyphCanvas(ch, color), Math.round(cx), Math.round(y), g.w * scale, 8 * scale);
        cx += (g.w + 1) * scale;
    }
    return cx - x;
}
/* break text into lines no wider than w font pixels */
function wrapText(s, w) {
    const out = [];
    for (const para of s.split('\n')) {
        let line = '';
        for (const word of para.split(' ')) {
            const t = line ? line + ' ' + word : word;
            if (textWidth(t) > w && line) { out.push(line); line = word; } else line = t;
        }
        out.push(line);
    }
    return out;
}
