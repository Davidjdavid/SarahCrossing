const FONT = {};
for (const line of FONT_SRC.split('\n')) {
    if (line.length < 3) continue;
    const ch = line[0], rest = line.slice(2);
    const rows = rest.split('|');
    FONT[ch] = { w: rows[0].length, rows };
}
FONT[' '] = { w: 3, rows: [] };
FONT['\u2014'] = { w: 6, rows: ['......', '......', '......', '######', '......', '......', '......', '......'] };    /* a dash, as in "Wipe your- oh" */
FONT['\u00a0'] = { w: 3, rows: [] };    /* a space that never breaks a line ("4 of 6") */
FONT['\xb7'] = { w: 3, rows: ['...', '...', '...', '.#.', '...', '...', '...', '...'] };    /* a middle dot, between the buttons on the title */
/* a few icons in the text: \x01 heart, \x02 arrow, \x03 button, \x04 spool */
FONT['\x01'] = { w: 7, rows: ['.##.##.', '#######', '#######', '.#####.', '..###..', '...#...', '.......', '.......'] };
FONT['\x02'] = { w: 4, rows: ['#...', '##..', '###.', '####', '###.', '##..', '#...', '....'] };
FONT['\x03'] = { w: 6, rows: ['.####.', '#....#', '#.##.#', '#.##.#', '#....#', '.####.', '......', '......'] };
FONT['\x04'] = { w: 6, rows: ['######', '.#..#.', '.####.', '.####.', '.#..#.', '######', '......', '......'] };

const TEXT_COLORS = {
    '': PAL.ink, ink: PAL.ink, white: PAL.white, cream: PAL.cream, red: PAL.red2, blue: PAL.blue3, green: PAL.green3,
    gold: PAL.gold2, purple: PAL.purple2, grey: PAL.grey3, teal: PAL.teal3, yellow: PAL.yellow, pink: PAL.pink2,
};

const Font = {
    cache: {},
    glyph(ch, col) {
        const k = col + ch;
        let c = this.cache[k];
        if (c) return c;
        const g = FONT[ch] || FONT['?'];
        c = Gfx.makeCanvas(g.w || 1, 8);
        const x = c.getContext('2d');
        x.fillStyle = col;
        g.rows.forEach((r, y) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') x.fillRect(i, y, 1, 1); });
        this.cache[k] = c;
        return c;
    },
    charW(ch) { const g = FONT[ch] || FONT['?']; return g.w + 1; },
    /* width of plain text (markup stripped) */
    width(s) { let w = 0; s = stripMarkup(s); for (const ch of s) w += this.charW(ch); return Math.max(0, w - 1); },
    /* draw text with {colour} markup; returns the x it ended at. limit: draw only the first n visible chars */
    draw(s, x, y, col = PAL.ink, limit = Infinity, shadow = null) {
        let cx = x, cur = col, n = 0;
        for (let i = 0; i < s.length; i++) {
            if (s[i] === '{') {
                const j = s.indexOf('}', i);
                if (j > i) { const name = s.slice(i + 1, j); cur = name === '/' ? col : (TEXT_COLORS[name] || PAL[name] || col); i = j; continue; }
            }
            if (n >= limit) break;
            const ch = s[i];
            if (ch !== ' ') {
                if (shadow) Gfx.img(this.glyph(ch, shadow), cx + 1, y + 1);
                Gfx.img(this.glyph(ch, cur), cx, y);
            }
            cx += this.charW(ch); n++;
        }
        return cx;
    },
    center(s, cx, y, col, shadow) { this.draw(s, Math.round(cx - this.width(s) / 2), y, col, Infinity, shadow); },
    /* break text into lines of at most maxW pixels (keeps markup) */
    wrap(s, maxW) {
        const out = [];
        for (const para of s.split('\n')) {
            let line = '';
            for (const word of para.split(' ')) {
                const cand = line ? line + ' ' + word : word;
                if (line && this.width(cand) > maxW) { out.push(line); line = word; }
                else line = cand;
            }
            out.push(line);
        }
        return out;
    },
};
function stripMarkup(s) { return s.replace(/\{[^}]*\}/g, ''); }
